export function detectLanguage(saved) {
  if (saved === "en" || saved === "uk") return saved;
  const browser = (chrome.i18n.getUILanguage() || navigator.language || "en").toLowerCase();
  return browser.startsWith("uk") ? "uk" : "en";
}

export function createTranslator(lang) {
  return (key, params = {}) => {
    const template = (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key;
    return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ""));
  };
}
